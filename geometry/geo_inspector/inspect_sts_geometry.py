#!/usr/bin/env python3
"""Extract STS sensor placements with external ROOT and join module grades."""

import argparse
import csv
import json
import math
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from utils.sts_naming import build_module_name_prefix


PROJECT_DIR = Path(__file__).resolve().parent
INPUT_DIR = PROJECT_DIR / 'data' / 'input'
OUTPUT_DIR = PROJECT_DIR / 'data' / 'output'

# Legacy station width: total number of ladder positions across the station.
STATION_WIDTHS = (8, 12, 12, 14, 14, 14, 16, 16)


# ---------------------------------------------------------------------------
# Geometry path patterns
# ---------------------------------------------------------------------------

# Legacy geometry hierarchy, e.g. v22d.
LEGACY_PATH_PATTERN = re.compile(
    r"/Unit(?P<unit>\d{2})(?P<side>[RL])_\d+"
    r"/LadderType(?P<type>\d{4})_(?P<copy>\d+)"
    r"/HalfLadder\d+[tb]_(?P<half>[12])"
    r"/HalfLadder\d+[tb]_Module\d+_(?P<module>\d+)"
    r"/Sensor\d+_(?P<sensor>\d+)$"
)

# New hierarchy introduced with v26a.
#
# Example:
#
# /top_1/sts_v26a_0
# /Unit07R_15
# /Ladder_LadderType36_603
# /HalfLadder_LadderType36_0
# /Module100_3
# /Sensor04_0
#
# Logical-volume identifiers are intentionally matched using \d+.
# Their number of digits is not part of the physical detector identity.
#
# Physical placement information is carried by the node-copy suffixes.
V26_PATH_PATTERN = re.compile(
    r"/Unit(?P<unit>\d{2})(?P<side>[RL])_\d+"
    r"/Ladder_LadderType(?P<type>\d+)_(?P<copy>\d+)"
    r"/HalfLadder_LadderType(?P=type)_(?P<half>[01])"
    r"/Module(?P<module_type>\d+)_(?P<module>\d+)"
    r"/Sensor(?P<sensor_type>\d+)_(?P<sensor>\d+)$"
)


NUMERIC_FIELDS = (
    'x',
    'y',
    'z',
    'dx',
    'dy',
    'dz',
)

ROTATION_FIELDS = tuple(
    f'r{i}{j}'
    for i in range(3)
    for j in range(3)
)


# ---------------------------------------------------------------------------
# Path parsing
# ---------------------------------------------------------------------------

def parse_legacy_sensor_path(match, path, naming_version):
    """Parse the legacy STS hierarchy, e.g. v22d."""

    values = match.groupdict()

    station = int(values['copy']) // 100 - 1
    slot = int(values['copy']) % 100 - 1

    if not 0 <= station < len(STATION_WIDTHS):
        raise ValueError(
            f'Invalid station copy number: {path}'
        )

    width = STATION_WIDTHS[station]
    side = values['side']

    if not 0 <= slot < width:
        raise ValueError(
            f'Invalid ladder slot: {path}'
        )

    if (slot < width // 2) != (side == 'R'):
        raise ValueError(
            f'Ladder copy number and unit side disagree: {path}'
        )

    ladder = (
        width // 2 - 1 - slot
        if side == 'R'
        else slot - width // 2
    )

    ladder_type = int(values['type'])

    if not 0 < ladder_type < 2000:
        raise ValueError(
            f'Unsupported ladder type: {path}'
        )

    # Legacy ladder type encodes the detector face.
    face = 'U' if ladder_type >= 1000 else 'D'

    old_unit = station + (face == 'U')

    physical_unit = (
        old_unit
        + (
            old_unit > 3
            or (old_unit == 3 and face == 'D')
        )
    )

    if int(values['unit']) != physical_unit:
        raise ValueError(
            f'Unit and station/face disagree for legacy geometry: {path}'
        )

    # Legacy half-ladder copies are one-based.
    half = 'T' if values['half'] == '1' else 'B'

    # Legacy module and sensor copies are one-based.
    module = int(values['module']) - 1
    sensor = int(values['sensor']) - 1

    if not 0 <= module <= 9 or sensor < 0:
        raise ValueError(
            f'Invalid module/sensor copy: {path}'
        )

    name = build_module_name_prefix(
        old_unit,
        face,
        side,
        slot + 1,
        half,
        module,
        version=naming_version,
    )

    key = (
        station,
        side,
        ladder,
        half,
        module,
    )

    return key, name, sensor


def parse_v26_sensor_path(match, path, naming_version):
    """Parse the hierarchy generated by the v26a geometry macro."""

    values = match.groupdict()

    side = values['side']
    physical_unit = int(values['unit'])
    copy_number = int(values['copy'])

    # ------------------------------------------------------------------
    # Ladder placement
    #
    # v26a generator:
    #
    # copyNo =
    #     100 * (ladderInfo.name.GetStation() + 1)
    #     + ladderInfo.name.GetIndex();
    #
    # Therefore:
    #
    #   hundreds -> station + 1
    #   remainder -> LadderName::GetIndex()
    # ------------------------------------------------------------------

    station = copy_number // 100 - 1
    ladder_index = copy_number % 100

    if not 0 <= station < len(STATION_WIDTHS):
        raise ValueError(
            f'Invalid station copy number: {path}'
        )

    width = STATION_WIDTHS[station]
    half_width = width // 2

    if not 0 <= ladder_index < half_width:
        raise ValueError(
            f'Invalid v26a ladder index {ladder_index} '
            f'for station {station}: {path}'
        )

    # ------------------------------------------------------------------
    # Recover upstream/downstream face.
    #
    # LadderName::GetStation():
    #
    #   downstream: station = raw_unit
    #   upstream:   station = raw_unit - 1
    #
    # LadderName::GetUnit() then converts raw unit into the mechanical
    # UnitXX index used in the TGeo hierarchy.
    #
    # Test both possibilities. Exactly one must match UnitXX.
    # ------------------------------------------------------------------

    candidates = []

    for face in ('D', 'U'):
        raw_unit = station + (face == 'U')

        expected_physical_unit = (
            raw_unit
            + (
                raw_unit > 3
                or (raw_unit == 3 and face == 'D')
            )
        )

        if expected_physical_unit == physical_unit:
            candidates.append((face, raw_unit))

    if len(candidates) != 1:
        raise ValueError(
            f'Cannot uniquely determine v26a face from '
            f'station={station}, unit={physical_unit}: {path}'
        )

    face, old_unit = candidates[0]

    # ------------------------------------------------------------------
    # Ladder normalization
    #
    # v26a LadderName::GetIndex() counts outwards from the beam pipe on
    # each side. The detector faces occupy alternating indices.
    #
    # Examples from the v26a configuration:
    #
    #   station 0 downstream:
    #       DL0, DR1, DL2, DR3
    #
    #   station 0 upstream:
    #       UR0, UL1, UR2, UL3
    #
    # The grade table likewise numbers ladders outwards, independently
    # on each side. The face alternation does not alter that number.
    # ------------------------------------------------------------------

    ladder = ladder_index


    # ------------------------------------------------------------------
    # Module naming
    #
    # build_module_name_prefix() expects the one-based, full-station
    # ladder slot used by the legacy generator. Its right-side slots run
    # from the outside in; its left-side slots run from the inside out.
    # Convert the new side-relative index before constructing the name.
    # ------------------------------------------------------------------

    slot = (
        half_width - ladder_index
        if side == 'R'
        else half_width + ladder_index + 1
    )

    # ------------------------------------------------------------------
    # Half ladder
    #
    # CreateLadder() places copy 0 at negative local Y (with a 180-degree
    # rotation) and copy 1 at positive local Y. The old generator places
    # its top half at positive local Y as well. Use the physical half,
    # rather than the misleading "Top copy" comment in the new macro.
    # ------------------------------------------------------------------

    half_copy = int(values['half'])

    if half_copy not in (0, 1):
        raise ValueError(
            f'Invalid v26a half-ladder copy: {path}'
        )

    half = 'T' if half_copy == 1 else 'B'

    # ------------------------------------------------------------------
    # Module
    #
    # ModuleXXX is a reusable logical-volume identifier.
    #
    # The physical module index is the AddNode() copy:
    #
    #   ModuleXXX_<moduleIdx>
    #
    # moduleIdx comes directly from the ladder layout index and is
    # already zero-based.
    # ------------------------------------------------------------------

    module = int(values['module'])

    if not 0 <= module <= 9:
        raise ValueError(
            f'Invalid module copy: {path}'
        )

    # ------------------------------------------------------------------
    # Sensor
    #
    # SensorXX identifies the logical sensor TYPE.
    #
    # ConstructModule() always places the physical sensor using:
    #
    #   module->AddNode(sensorVol, 0, ...)
    #
    # Therefore the final node copy is expected to be zero.
    # ------------------------------------------------------------------

    sensor = int(values['sensor'])

    if sensor != 0:
        raise ValueError(
            f'Unexpected v26a sensor copy {sensor}: {path}'
        )

    name = build_module_name_prefix(
        old_unit,
        face,
        side,
        slot,
        half,
        module,
        version=naming_version,
    )

    key = (
        station,
        side,
        ladder,
        half,
        module,
    )

    return key, name, sensor


def parse_sensor_path(path, naming_version='STS3_5'):
    """Parse either the legacy or v26a+ STS sensor hierarchy."""

    match = LEGACY_PATH_PATTERN.search(path)

    if match:
        return parse_legacy_sensor_path(
            match,
            path,
            naming_version,
        )

    match = V26_PATH_PATTERN.search(path)

    if match:
        return parse_v26_sensor_path(
            match,
            path,
            naming_version,
        )

    raise ValueError(
        f'Unsupported STS sensor path: {path}'
    )


# ---------------------------------------------------------------------------
# Grade table
# ---------------------------------------------------------------------------

def read_grades(path):
    grades = {}

    with Path(path).open() as stream:
        header = next(stream, '').split()

        expected_header = [
            'station(unit)',
            'l/r',
            'ladder',
            't/b',
            'module',
            'size',
            'grade',
        ]

        if header != expected_header:
            raise ValueError(
                'Unexpected grade table header'
            )

        for line_number, line in enumerate(stream, 2):
            if not line.strip():
                continue

            fields = line.split()

            if len(fields) != 7:
                raise ValueError(
                    f'Grade line {line_number}: '
                    f'expected seven columns'
                )

            (
                station,
                side,
                ladder,
                half,
                module,
                size,
                grade,
            ) = fields

            key = (
                int(station),
                side,
                int(ladder),
                half,
                int(module),
            )

            size = float(size)

            if (
                not 0 <= key[0] < len(STATION_WIDTHS)
                or side not in ('L', 'R')
                or not 0 <= key[2] < STATION_WIDTHS[key[0]] // 2
                or half not in ('T', 'B')
                or not 0 <= key[4] <= 9
                or not math.isfinite(size)
                or size <= 0
                or not grade
            ):
                raise ValueError(
                    f'Invalid grade line {line_number}: '
                    f'{line.strip()}'
                )

            if key in grades:
                raise ValueError(
                    f'Duplicate grade key at line '
                    f'{line_number}: {key}'
                )

            grades[key] = (
                size,
                grade,
            )

    if not grades:
        raise ValueError(
            'Grade table is empty'
        )

    return grades


# ---------------------------------------------------------------------------
# Join geometry and grade information
# ---------------------------------------------------------------------------

def join_sensors(
    sensor_csv,
    grades,
    naming_version='STS3_5',
    include_path=False,
):
    result = []
    seen = set()
    size_mismatch_count = 0

    with Path(sensor_csv).open(newline='') as stream:
        reader = csv.DictReader(stream)

        required = {
            'node_path',
            *NUMERIC_FIELDS,
            *ROTATION_FIELDS,
        }

        if not required.issubset(reader.fieldnames or []):
            raise ValueError(
                f'Sensor CSV requires columns: '
                f'{sorted(required)}'
            )

        for raw in reader:
            path = raw['node_path']

            key, name, sensor = parse_sensor_path(
                path,
                naming_version,
            )

            # Both supported generators have one physical sensor per module.
            if sensor != 0:
                raise ValueError(
                    f'Expected one sensor per module: {path}'
                )

            if key in seen:
                raise ValueError(
                    f'Duplicate module key {key}: {path}'
                )

            seen.add(key)

            if key not in grades:
                raise ValueError(
                    f'No grade for module {name}, '
                    f'table key {key}: {path}'
                )

            numbers = {
                field: float(raw[field])
                for field in (
                    *NUMERIC_FIELDS,
                    *ROTATION_FIELDS,
                )
            }

            if not all(
                math.isfinite(value)
                for value in numbers.values()
            ):
                raise ValueError(
                    f'Nonfinite geometry values: {path}'
                )

            if any(
                numbers[field] <= 0
                for field in ('dx', 'dy', 'dz')
            ):
                raise ValueError(
                    f'Nonpositive sensor dimensions: {path}'
                )

            grade_size, grade = grades[key]

            # --------------------------------------------------------------
            # Sensor-size consistency check
            #
            # The ROOT geometry is authoritative.
            #
            # A discrepancy in the grade table is reported to the user but
            # does NOT prevent output generation.
            # --------------------------------------------------------------

            if not math.isclose(
                numbers['dy'],
                grade_size,
                rel_tol=0,
                abs_tol=1e-6,
            ):
                size_mismatch_count += 1

                print(
                    f'WARNING: Sensor size mismatch for {name}: '
                    f'geometry {numbers["dy"]}, '
                    f'grade table {grade_size}; '
                    f'using geometry value',
                    file=sys.stderr,
                )

            row = dict(
                module_name=name,
                station=key[0],
                side=key[1],
                ladder=key[2],
                half=key[3],
                module=key[4],
                grade=grade,
                **numbers,
            )

            if include_path:
                row['node_path'] = path

            result.append(row)

    missing = grades.keys() - seen

    if missing:
        raise ValueError(
            f'{len(missing)} grade entries have no sensor; '
            f'examples: {sorted(missing)[:5]}'
        )

    if not result:
        raise ValueError(
            'No sensors were found'
        )

    if size_mismatch_count:
        print(
            f'WARNING: {size_mismatch_count} sensor size mismatch(es) '
            f'were found; ROOT geometry dimensions were used.',
            file=sys.stderr,
        )

    return sorted(
        result,
        key=lambda row: (
            row['station'],
            row['side'],
            row['ladder'],
            row['half'],
            row['module'],
        ),
    )


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main(argv=None):
    parser = argparse.ArgumentParser(
        description=__doc__,
    )

    inputs = parser.add_mutually_exclusive_group(
        required=True,
    )

    inputs.add_argument(
        '--geometry',
        type=Path,
        help='ROOT geometry file',
    )

    inputs.add_argument(
        '--sensor-csv',
        type=Path,
        help='CSV already produced by the ROOT macro',
    )

    parser.add_argument(
        '--grades',
        type=Path,
        default=INPUT_DIR / 'uli_new_grades.txt',
    )

    parser.add_argument(
        '--output',
        type=Path,
        default=Path('module_geometry_grades.csv'),
        help=(
            'Output filename relative to '
            'geo_inspector/data/output, '
            'or an absolute path'
        ),
    )

    parser.add_argument(
        '--naming-version',
        choices=('STS8', 'STS3_5'),
        default='STS3_5',
    )

    parser.add_argument(
        '--include-path',
        action='store_true',
    )

    parser.add_argument(
        '--root',
        default='root',
        help=(
            'ROOT executable from your external environment'
        ),
    )

    args = parser.parse_args(argv)

    if not args.output.is_absolute():
        args.output = OUTPUT_DIR / args.output

    try:
        # ------------------------------------------------------------------
        # Validate inputs
        # ------------------------------------------------------------------

        for source in (
            args.geometry,
            args.sensor_csv,
            args.grades,
        ):
            if (
                source
                and source.resolve() == args.output.resolve()
            ):
                raise ValueError(
                    'Output must differ from all input files'
                )

        grades = read_grades(
            args.grades
        )

        # ------------------------------------------------------------------
        # Extract geometry
        # ------------------------------------------------------------------

        with tempfile.TemporaryDirectory(
            prefix='sts-inspector-'
        ) as directory:

            sensor_csv = args.sensor_csv

            if args.geometry:
                if not args.geometry.is_file():
                    raise ValueError(
                        f'Geometry file does not exist: '
                        f'{args.geometry}'
                    )

                root = shutil.which(
                    args.root
                )

                if root is None:
                    raise ValueError(
                        'ROOT executable not found; '
                        'set up your ROOT environment first '
                        'or use --root'
                    )

                sensor_csv = (
                    Path(directory)
                    / 'sensors.csv'
                )

                # Fixed wrapper avoids embedding user paths into ROOT
                # command-line syntax.
                macro = (
                    Path(__file__)
                    .with_name('extract_sts_sensors.C')
                    .resolve()
                )

                wrapper = (
                    Path(directory)
                    / 'run_extract.C'
                )

                wrapper.write_text(
                    f'#include {json.dumps(str(macro))}\n'
                    'void run_extract() { '
                    'extract_sts_sensors('
                    f'{json.dumps(str(args.geometry.resolve()))}, '
                    f'{json.dumps(str(sensor_csv))}'
                    '); }\n'
                )

                subprocess.run(
                    [
                        root,
                        '-l',
                        '-b',
                        '-q',
                        str(wrapper),
                    ],
                    check=True,
                )

            # ----------------------------------------------------------------
            # Join geometry and grade data
            # ----------------------------------------------------------------

            rows = join_sensors(
                sensor_csv,
                grades,
                args.naming_version,
                args.include_path,
            )

        # ------------------------------------------------------------------
        # Write output atomically
        # ------------------------------------------------------------------

        args.output.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        with tempfile.NamedTemporaryFile(
            mode='w',
            newline='',
            dir=args.output.resolve().parent,
            delete=False,
        ) as stream:

            temporary = Path(
                stream.name
            )

            try:
                writer = csv.DictWriter(
                    stream,
                    fieldnames=list(rows[0]),
                )

                writer.writeheader()
                writer.writerows(rows)

                stream.close()

                temporary.replace(
                    args.output
                )

            finally:
                temporary.unlink(
                    missing_ok=True
                )

        print(
            f'Wrote {len(rows)} modules to '
            f'{args.output} '
            f'(cm, full sensor dimensions)'
        )

        return 0

    except (
        OSError,
        ValueError,
        subprocess.CalledProcessError,
    ) as error:

        print(
            f'inspect_sts_geometry: {error}',
            file=sys.stderr,
        )

        return 1


if __name__ == '__main__':
    sys.exit(main())
